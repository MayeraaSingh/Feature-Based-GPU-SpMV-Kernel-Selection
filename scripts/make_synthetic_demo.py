#!/usr/bin/env python
"""
make_synthetic_demo.py
======================
Write a small set of SYNTHETIC input CSVs plus a matching config so the selector
pipeline can be tried before Member 1 delivers real GPU timings.

The timings come from an invented formula. They are NOT measurements and every
downstream output is stamped "SYNTHETIC DATA - NOT A RESULT". The timings file
is named ``SYNTHETIC_kernel_timings.csv`` on purpose; the training and
evaluation scripts refuse such a file unless ``--allow-synthetic`` is passed.

Usage
-----
    python scripts/make_synthetic_demo.py [OUT_DIR]        # default: data/synthetic_demo
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from selector.config import DEFAULT_CONFIG_PATH  # noqa: E402


def _load_write_files():
    """Load the synthetic generator by FILE PATH, not by the package name ``tests``.

    Another package called ``tests`` (e.g. Colab's dist-packages) can shadow ours; a
    path-based load cannot be shadowed.
    """
    path = ROOT / "tests" / "fixtures" / "synthetic_timings.py"
    spec = importlib.util.spec_from_file_location("spmv_synthetic_timings", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.write_files


write_files = _load_write_files()


def _display(path: Path) -> str:
    """Path relative to the project root when possible (keeps commands short)."""
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path.resolve())


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    out = Path(argv[0]) if argv else ROOT / "data" / "synthetic_demo"
    paths = write_files(out)

    cfg = yaml.safe_load(DEFAULT_CONFIG_PATH.read_text(encoding="utf-8"))
    cfg["paths"] = {key: _display(p) for key, p in paths.items()}
    cfg["selector"]["grid"] = {"n_estimators": [50, 100], "max_depth": [None, 3]}  # small: fast demo
    cfg["evaluation"]["bootstrap_samples"] = 500
    config_path = out / "demo_config.yaml"
    header = "# SYNTHETIC DEMO CONFIG - generated by scripts/make_synthetic_demo.py\n"
    config_path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")

    cfg_arg = _display(config_path)
    print("Wrote SYNTHETIC demo inputs (NOT real data):")
    for p in [*paths.values(), config_path]:
        print(f"  {_display(p)}")
    print("\nTrain, then evaluate:")
    print(f"  python scripts/train_selector.py --config {cfg_arg} --allow-synthetic --run-id demo")
    print(f"  python scripts/evaluate_generalization.py --config {cfg_arg} --allow-synthetic --run-dir results/demo")
    return 0


if __name__ == "__main__":
    sys.exit(main())
